"""Adapt KernelAgent's kernel_function output to KernelBench's ModelNew API."""

from __future__ import annotations

import ast


def wrap_kernel_for_kernelbench(reference_source: str, kernel_source: str) -> str:
    """Return source exposing a KernelBench-compatible ``ModelNew`` class.

    KernelAgent's Fuser emits ``kernel_function(...)``. KernelBench's official
    evaluator imports a ``ModelNew`` class, so this wrapper calls the generated
    function and forwards initialized model parameters/buffers only when its
    required positional signature needs them. The adapter is static code and
    must be verified on A30 against representative L1 tasks.
    """
    tree = ast.parse(kernel_source)
    class_names = {
        node.name for node in tree.body if isinstance(node, ast.ClassDef)
    }
    function_names = {
        node.name for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }
    if "ModelNew" in class_names:
        return kernel_source.rstrip() + "\n"
    if "kernel_function" not in function_names:
        raise ValueError("KernelAgent output must define kernel_function(...) or ModelNew")

    reference_literal = repr(reference_source)
    wrapper = f'''

# KernelBench ModelNew adapter generated by kernelbench_runner.
import inspect as _kb_inspect
import types as _kb_types
import torch as _kb_torch

_kb_reference_module = _kb_types.ModuleType("_kernelbench_reference")
exec({reference_literal}, _kb_reference_module.__dict__)


class ModelNew(_kb_torch.nn.Module):
    def __init__(self, *init_args, **init_kwargs):
        super().__init__()
        self._kernelbench_reference_model = _kb_reference_module.Model(
            *init_args, **init_kwargs
        )

    def forward(self, *inputs):
        signature = _kb_inspect.signature(kernel_function)
        positional = [
            parameter
            for parameter in signature.parameters.values()
            if parameter.kind in (
                _kb_inspect.Parameter.POSITIONAL_ONLY,
                _kb_inspect.Parameter.POSITIONAL_OR_KEYWORD,
            )
        ]
        required_count = sum(
            parameter.default is _kb_inspect.Parameter.empty
            for parameter in positional
        )
        additional_count = max(0, required_count - len(inputs))
        state = list(self._kernelbench_reference_model.parameters())
        state.extend(self._kernelbench_reference_model.buffers())
        if additional_count > len(state):
            raise TypeError(
                "kernel_function requires more positional inputs than the task "
                "inputs and initialized model state provide"
            )
        return kernel_function(*inputs, *state[:additional_count])
'''
    return kernel_source.rstrip() + wrapper
